"""IR -> PowerPoint (.pptx) via python-pptx. One idea per slide; long tables paginate."""
from __future__ import annotations

from pathlib import Path

from PIL import Image
from pptx import Presentation
from pptx.dml.color import RGBColor
from pptx.enum.shapes import MSO_SHAPE
from pptx.enum.text import MSO_ANCHOR, PP_ALIGN
from pptx.util import Emu, Inches, Pt

from ..ir import Callout, Chart, Commentary, Document, KPIGrid, Paragraph, Table
from . import theme as T

W, H = Inches(13.333), Inches(7.5)
MARGIN = Inches(0.6)
ROWS_PER_SLIDE = 9


def _rgb(h: str) -> RGBColor:
    return RGBColor.from_string(h)


def _text(slide, x, y, w, h, text, size=14, bold=False, color=T.INK, align=PP_ALIGN.LEFT,
          anchor=MSO_ANCHOR.TOP, italic=False):
    box = slide.shapes.add_textbox(x, y, w, h)
    tf = box.text_frame
    tf.word_wrap = True
    tf.vertical_anchor = anchor
    tf.margin_left = tf.margin_right = 0
    p = tf.paragraphs[0]
    p.alignment = align
    r = p.add_run()
    r.text = text
    r.font.size, r.font.bold, r.font.italic = Pt(size), bold, italic
    r.font.color.rgb = _rgb(color)
    r.font.name = "Calibri"
    return box


class _Deck:
    def __init__(self, doc: Document) -> None:
        self.doc = doc
        self.prs = Presentation()
        self.prs.slide_width, self.prs.slide_height = W, H
        self.blank = self.prs.slide_layouts[6]
        self.n = 0

    def slide(self, title: str, subtitle: str | None = None):
        s = self.prs.slides.add_slide(self.blank)
        self.n += 1
        bar = s.shapes.add_shape(MSO_SHAPE.RECTANGLE, 0, 0, Inches(0.18), H)
        bar.fill.solid()
        bar.fill.fore_color.rgb = _rgb(T.NAVY)
        bar.line.fill.background()
        _text(s, MARGIN, Inches(0.38), W - 2 * MARGIN, Inches(0.7), title, 26, True, T.NAVY)
        if subtitle:
            _text(s, MARGIN, Inches(1.05), W - 2 * MARGIN, Inches(0.6), subtitle, 13, False, T.INK_2)
        _text(s, MARGIN, H - Inches(0.45), Inches(9), Inches(0.3),
              f"{self.doc.scheme_name}  |  {self.doc.title}  |  {self.doc.period_label}", 9, color=T.INK_3)
        _text(s, W - MARGIN - Inches(1), H - Inches(0.45), Inches(1), Inches(0.3), str(self.n + 1), 9,
              color=T.INK_3, align=PP_ALIGN.RIGHT)
        return s

    def body_top(self, subtitle: str | None) -> Emu:
        return Inches(1.75) if subtitle else Inches(1.3)


def render_pptx(doc: Document, path: Path) -> Path:
    deck = _Deck(doc)
    _cover(deck)
    for section in doc.sections:
        pending_lead: str | None = None
        for block in section.blocks:
            if isinstance(block, Paragraph) and block.style in {"lead", "body"}:
                if pending_lead:  # two paragraphs in a row -> text slide
                    _text_slide(deck, section.title, pending_lead)
                pending_lead = block.text
                continue
            sub, pending_lead = pending_lead, None
            if isinstance(block, KPIGrid):
                _kpi_slide(deck, section.title, block, sub)
            elif isinstance(block, Commentary):
                _commentary_slide(deck, section.title, block)
            elif isinstance(block, Table):
                _table_slides(deck, block.caption or section.title, block, sub)
            elif isinstance(block, Chart) and block.image:
                _chart_slide(deck, block.title or section.title, block, sub)
            elif isinstance(block, Callout):
                _text_slide(deck, section.title, block.text, T.WARN_INK)
            elif isinstance(block, Paragraph):  # note
                _text_slide(deck, section.title, block.text, T.INK_2, 14)
        if pending_lead:
            _text_slide(deck, section.title, pending_lead)
    path.parent.mkdir(parents=True, exist_ok=True)
    deck.prs.save(path)
    return path


def _cover(deck: _Deck) -> None:
    s = deck.prs.slides.add_slide(deck.blank)
    bg = s.shapes.add_shape(MSO_SHAPE.RECTANGLE, 0, 0, W, H)
    bg.fill.solid()
    bg.fill.fore_color.rgb = _rgb(T.NAVY)
    bg.line.fill.background()
    accent = s.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(0.9), Inches(3.55), Inches(1.4), Inches(0.08))
    accent.fill.solid()
    accent.fill.fore_color.rgb = _rgb(T.ACCENT)
    accent.line.fill.background()
    d = deck.doc
    _text(s, Inches(0.9), Inches(1.6), Inches(11), Inches(0.5), d.scheme_name.upper(), 16, True, "9EC5F4")
    _text(s, Inches(0.9), Inches(2.1), Inches(11.5), Inches(1.3), d.title, 44, True, "FFFFFF")
    _text(s, Inches(0.9), Inches(3.85), Inches(11), Inches(0.6), d.subtitle, 20, False, "DCE6F2")
    _text(s, Inches(0.9), Inches(6.4), Inches(11), Inches(0.4),
          f"Prepared for {d.prepared_for}  ·  Generated by Ledgerline from reconciled source data", 12, False, "B7C6D8")


def _kpi_slide(deck: _Deck, title: str, block: KPIGrid, sub: str | None) -> None:
    s = deck.slide(title, sub)
    n = len(block.items)
    gap = Inches(0.25)
    top = deck.body_top(sub) + Inches(0.4)
    card_w = int((W - 2 * MARGIN - gap * (n - 1)) / n)
    card_h = Inches(2.3)
    for i, k in enumerate(block.items):
        x = MARGIN + i * (card_w + gap)
        card = s.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, x, top, card_w, card_h)
        card.adjustments[0] = 0.06
        card.fill.solid()
        card.fill.fore_color.rgb = _rgb(T.BAND)
        card.line.fill.background()
        pad = Inches(0.25)
        _text(s, x + pad, top + Inches(0.25), card_w - 2 * pad, Inches(0.6), k.label.upper(), 11, True, T.INK_2)
        _text(s, x + pad, top + Inches(0.8), card_w - 2 * pad, Inches(0.9), k.display, 30 if n <= 4 else 26, True, T.NAVY)
        if k.sub:
            _text(s, x + pad, top + Inches(1.65), card_w - 2 * pad, Inches(0.5), k.sub, 12, False,
                  T.TONE_HEX.get(k.tone, T.INK_2))


def _commentary_slide(deck: _Deck, title: str, block: Commentary) -> None:
    s = deck.slide(title)
    box = _text(s, MARGIN, Inches(1.4), W - 2 * MARGIN, Inches(4.9), block.text, 17, False, T.INK)
    box.text_frame.paragraphs[0].line_spacing = 1.25
    mark = "✓ " if block.status == "verified" else "ⓘ "
    _text(s, MARGIN, Inches(6.4), W - 2 * MARGIN, Inches(0.5), mark + T.status_line(block.status, block.provider, block.issues),
          11, False, T.GOOD if block.status == "verified" else T.WARN_INK, italic=True)


def _text_slide(deck: _Deck, title: str, text: str, color: str = T.INK, size: int = 18) -> None:
    s = deck.slide(title)
    _text(s, MARGIN, Inches(1.5), W - 2 * MARGIN, Inches(4.8), text, size, False, color)


def _chart_slide(deck: _Deck, title: str, block: Chart, sub: str | None) -> None:
    s = deck.slide(title, sub)
    top = deck.body_top(sub)
    max_w, max_h = W - 2 * MARGIN, H - top - Inches(0.9) - (Inches(0.35) if block.caption else 0)
    with Image.open(block.image) as im:
        iw, ih = im.size
    scale = min(max_w / iw, max_h / ih)
    w, h = int(iw * scale), int(ih * scale)
    s.shapes.add_picture(block.image, int((W - w) / 2), top, w, h)
    if block.caption:
        _text(s, MARGIN, top + h + Inches(0.08), W - 2 * MARGIN, Inches(0.35), block.caption, 11, color=T.INK_3, italic=True)


def _table_slides(deck: _Deck, title: str, block: Table, sub: str | None) -> None:
    chunks = [block.rows[i:i + ROWS_PER_SLIDE] for i in range(0, len(block.rows), ROWS_PER_SLIDE)] or [[]]
    for ci, rows in enumerate(chunks):
        t_title = title + (f" (cont.)" if ci else "")
        s = deck.slide(t_title, sub if ci == 0 else None)
        top = deck.body_top(sub if ci == 0 else None) + Inches(0.1)
        ncols = len(block.columns)
        width = W - 2 * MARGIN
        row_h = Inches(0.42)
        shape = s.shapes.add_table(len(rows) + 1, ncols, MARGIN, top, width, row_h * (len(rows) + 1))
        table = shape.table
        first = 0.26 if ncols > 4 else 0.4
        if block.columns and block.columns[-1] in {"Reason", "How it is calculated", "Built from"}:
            first = 0.18
        widths = [first] + [(1 - first) / (ncols - 1)] * (ncols - 1)
        if block.columns[-1] == "Built from" or block.columns[-1] == "Reason":
            widths = [first] + [(1 - first - 0.3) / (ncols - 2)] * (ncols - 2) + [0.3]
        for i, wfrac in enumerate(widths):
            table.columns[i].width = int(width * wfrac)
        size = 11 if ncols <= 6 else 10
        for i, col in enumerate(block.columns):
            c = table.cell(0, i)
            c.fill.solid()
            c.fill.fore_color.rgb = _rgb(T.NAVY)
            _cell_text(c, col, size, True, "FFFFFF", PP_ALIGN.LEFT if i == 0 else PP_ALIGN.RIGHT)
        for r, row in enumerate(rows, start=1):
            for i, cell in enumerate(row):
                c = table.cell(r, i)
                c.fill.solid()
                c.fill.fore_color.rgb = _rgb(T.BAND if cell.bold else ("FFFFFF" if r % 2 else "FAFAF8"))
                _cell_text(c, cell.text, size, cell.bold, T.TONE_HEX.get(cell.tone, T.INK),
                           PP_ALIGN.LEFT if cell.align == "left" else PP_ALIGN.RIGHT)
        if block.note and ci == len(chunks) - 1:
            _text(s, MARGIN, H - Inches(1.05), W - 2 * MARGIN, Inches(0.5), block.note, 10, color=T.INK_3, italic=True)


def _cell_text(cell, text, size, bold, color, align) -> None:
    cell.margin_left = cell.margin_right = Inches(0.08)
    cell.margin_top = cell.margin_bottom = Inches(0.04)
    cell.vertical_anchor = MSO_ANCHOR.MIDDLE
    tf = cell.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    p.alignment = align
    r = p.add_run()
    r.text = text
    r.font.size, r.font.bold = Pt(size), bold
    r.font.color.rgb = _rgb(color)
    r.font.name = "Calibri"
