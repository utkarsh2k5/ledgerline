"""IR -> Word (.docx) via python-docx."""
from __future__ import annotations

from pathlib import Path

from docx import Document as DocxDocument
from docx.enum.section import WD_ORIENT
from docx.enum.table import WD_TABLE_ALIGNMENT, WD_CELL_VERTICAL_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_BREAK
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Cm, Pt, RGBColor

from ..ir import KPIGrid, Callout, Chart, Commentary, Document, Paragraph, Table
from . import theme as T


def _rgb(hex_: str) -> RGBColor:
    return RGBColor.from_string(hex_)


def _shade(cell, hex_: str) -> None:
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_)
    tcPr.append(shd)


def _cell_margins(table, top=60, bottom=60, left=90, right=90) -> None:
    tblPr = table._tbl.tblPr
    mar = OxmlElement("w:tblCellMar")
    for side, v in (("top", top), ("bottom", bottom), ("left", left), ("right", right)):
        el = OxmlElement(f"w:{side}")
        el.set(qn("w:w"), str(v))
        el.set(qn("w:type"), "dxa")
        mar.append(el)
    tblPr.append(mar)


def _borders(table, color=T.RULE, inside_h=True) -> None:
    tblPr = table._tbl.tblPr
    borders = OxmlElement("w:tblBorders")
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        el = OxmlElement(f"w:{edge}")
        visible = edge in ("bottom",) or (edge == "insideH" and inside_h) or edge == "top"
        el.set(qn("w:val"), "single" if visible else "nil")
        el.set(qn("w:sz"), "4")
        el.set(qn("w:color"), color)
        borders.append(el)
    tblPr.append(borders)


def _run(par, text: str, size: float = 9.5, bold=False, color=T.INK, italic=False):
    r = par.add_run(text)
    r.font.size = Pt(size)
    r.bold = bold
    r.italic = italic
    r.font.color.rgb = _rgb(color)
    return r


# python-docx has no API for this, hence the raw XML.
def _repeat_header(row) -> None:
    trPr = row._tr.get_or_add_trPr()
    el = OxmlElement("w:tblHeader")
    el.set(qn("w:val"), "true")
    trPr.append(el)


def _page_number_field(par) -> None:
    for kind, text in (("begin", None), ("instr", " PAGE "), ("end", None)):
        if kind == "instr":
            r = par.add_run()
            instr = OxmlElement("w:instrText")
            instr.set(qn("xml:space"), "preserve")
            instr.text = text
            r._r.append(instr)
        else:
            r = par.add_run()
            fc = OxmlElement("w:fldChar")
            fc.set(qn("w:fldCharType"), kind)
            r._r.append(fc)
        r.font.size = Pt(8)
        r.font.color.rgb = _rgb(T.INK_3)


def render_docx(doc: Document, path: Path) -> Path:
    d = DocxDocument()
    sec = d.sections[0]
    sec.orientation = WD_ORIENT.PORTRAIT
    sec.page_width, sec.page_height = Cm(21.0), Cm(29.7)
    sec.left_margin = sec.right_margin = Cm(2.0)
    sec.top_margin, sec.bottom_margin = Cm(1.8), Cm(1.8)
    content_width = Cm(17.0)

    normal = d.styles["Normal"]
    normal.font.name = "Calibri"
    normal.element.rPr.rFonts.set(qn("w:eastAsia"), "Calibri")
    normal.font.size = Pt(10)
    normal.paragraph_format.space_after = Pt(4)
    for lvl, size in ((1, 15), (2, 12)):
        st = d.styles[f"Heading {lvl}"]
        st.font.name = "Calibri"
        st.font.size = Pt(size)
        st.font.bold = True
        st.font.color.rgb = _rgb(T.NAVY)
        st.paragraph_format.space_before = Pt(14 if lvl == 1 else 8)
        st.paragraph_format.space_after = Pt(6)
        st.paragraph_format.keep_with_next = True

    # footer
    fp = sec.footer.paragraphs[0]
    fp.alignment = WD_ALIGN_PARAGRAPH.LEFT
    _run(fp, f"{doc.scheme_name}  |  {doc.title}  |  {doc.period_label}  |  Confidential  |  Page ", 8, color=T.INK_3)
    _page_number_field(fp)

    # cover
    sec.different_first_page_header_footer = True
    for _ in range(6):
        d.add_paragraph()
    p = d.add_paragraph()
    _run(p, doc.scheme_name.upper(), 11, True, T.ACCENT)
    p = d.add_paragraph()
    _run(p, doc.title, 30, True, T.NAVY)
    p = d.add_paragraph()
    _run(p, doc.subtitle, 14, False, T.INK_2)
    p.paragraph_format.space_after = Pt(40)
    rule = d.add_table(rows=1, cols=1)
    _borders(rule, T.NAVY, inside_h=False)
    rule.rows[0].height = Cm(0.1)
    p = d.add_paragraph()
    p.paragraph_format.space_before = Pt(18)
    _run(p, f"Prepared for: {doc.prepared_for}", 10, color=T.INK_2)
    p = d.add_paragraph()
    _run(p, "Generated by Ledgerline from reconciled source data. Every figure is traceable to its source.", 9, color=T.INK_3, italic=True)
    d.add_paragraph().add_run().add_break(WD_BREAK.PAGE)

    for section in doc.sections:
        d.add_heading(section.title, level=1)
        for block in section.blocks:
            if isinstance(block, KPIGrid):
                _kpis(d, block, content_width)
            elif isinstance(block, Table):
                _table(d, block, content_width)
            elif isinstance(block, Chart):
                if block.image:
                    if block.title and block.title != section.title:
                        d.add_heading(block.title, level=2)
                    d.add_picture(block.image, width=content_width)
                    if block.caption:
                        p = d.add_paragraph()
                        _run(p, block.caption, 8, color=T.INK_3, italic=True)
            elif isinstance(block, Commentary):
                for para in block.text.split("\n\n"):
                    p = d.add_paragraph()
                    p.paragraph_format.line_spacing = 1.2
                    _run(p, para.strip(), 10.5)
                p = d.add_paragraph()
                _run(p, ("✓ " if block.status == "verified" else "ⓘ ") + T.status_line(block.status, block.provider, block.issues),
                     8, color=T.GOOD if block.status == "verified" else T.WARN_INK, italic=True)
            elif isinstance(block, Callout):
                t = d.add_table(rows=1, cols=1)
                t.alignment = WD_TABLE_ALIGNMENT.CENTER
                _shade(t.cell(0, 0), T.WARN_BG)
                _cell_margins(t, 120, 120, 160, 160)
                _run(t.cell(0, 0).paragraphs[0], block.text, 10, color=T.WARN_INK)
                d.add_paragraph()
            elif isinstance(block, Paragraph):
                p = d.add_paragraph()
                if block.style == "note":
                    _run(p, block.text, 8.5, color=T.INK_3, italic=True)
                elif block.style == "lead":
                    _run(p, block.text, 10.5, color=T.INK_2)
                else:
                    _run(p, block.text, 10)
    path.parent.mkdir(parents=True, exist_ok=True)
    d.core_properties.title = f"{doc.title} - {doc.scheme_name}"
    d.core_properties.author = "Ledgerline"
    d.save(path)
    return path


def _kpis(d, block: KPIGrid, width) -> None:
    n = len(block.items)
    t = d.add_table(rows=1, cols=n)
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    _borders(t, T.RULE, inside_h=False)
    _cell_margins(t, 120, 120, 120, 120)
    for i, k in enumerate(block.items):
        c = t.cell(0, i)
        c.width = int(width / n)
        _shade(c, T.BAND)
        p = c.paragraphs[0]
        _run(p, k.label.upper(), 7.5, True, T.INK_2)
        p = c.add_paragraph()
        p.paragraph_format.space_before = Pt(2)
        _run(p, k.display, 17, True, T.NAVY)
        if k.sub:
            p = c.add_paragraph()
            _run(p, k.sub, 8, color=T.TONE_HEX.get(k.tone, T.INK_2))
    d.add_paragraph()


def _table(d, block: Table, width) -> None:
    if block.caption:
        d.add_heading(block.caption, level=2)
    ncols = len(block.columns)
    t = d.add_table(rows=1, cols=ncols)
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    _borders(t)
    _cell_margins(t)
    hdr = t.rows[0]
    _repeat_header(hdr)
    first_w = 0.28 if ncols > 4 else 0.4
    widths = [width * first_w] + [width * (1 - first_w) / (ncols - 1)] * (ncols - 1)
    small = ncols >= 7
    for i, col in enumerate(block.columns):
        c = hdr.cells[i]
        c.width = int(widths[i])
        _shade(c, T.NAVY)
        p = c.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT if i == 0 else WD_ALIGN_PARAGRAPH.RIGHT
        _run(p, col, 7.5 if small else 8.5, True, "FFFFFF")
    for r_i, row in enumerate(block.rows):
        cells = t.add_row().cells
        for i, cell in enumerate(row):
            c = cells[i]
            c.width = int(widths[i])
            c.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            if cell.bold:
                _shade(c, T.BAND)
            p = c.paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT if cell.align == "left" else WD_ALIGN_PARAGRAPH.RIGHT
            _run(p, cell.text, 7.5 if small else 9, cell.bold, T.TONE_HEX.get(cell.tone, T.INK))
    if block.note:
        p = d.add_paragraph()
        p.paragraph_format.space_before = Pt(3)
        _run(p, block.note, 8, color=T.INK_3, italic=True)
    d.add_paragraph()
